"""Writes scripts/sprite_crops.gd: the visible (non-transparent) rectangle of
each big sprite. The werecat layers all share an 800x800 canvas but most of
each one is empty; drawing only the cropped region keeps their positions
exactly the same while cutting the GPU's blending work several times over.

Run after tools/gen_art.py:  python3 tools/gen_crops.py
"""
import glob
import os

from PIL import Image

ROOT = os.path.join(os.path.dirname(__file__), "..")
PAD = 2
rows = []
for f in sorted(glob.glob(os.path.join(ROOT, "assets", "sprites", "*.png"))):
    im = Image.open(f).convert("RGBA")
    w, h = im.size
    if w * h < 160 * 160:
        continue
    bb = im.getchannel("A").point(lambda a: 255 if a > 1 else 0).getbbox()
    if bb is None:
        continue
    x0, y0 = max(0, bb[0] - PAD), max(0, bb[1] - PAD)
    x1, y1 = min(w, bb[2] + PAD), min(h, bb[3] + PAD)
    if (x1 - x0) * (y1 - y0) > 0.85 * w * h:
        continue  # not worth it
    name = os.path.splitext(os.path.basename(f))[0]
    rows.append(f'\t"{name}": Rect2({x0}, {y0}, {x1 - x0}, {y1 - y0}),')

out = os.path.join(ROOT, "scripts", "sprite_crops.gd")
with open(out, "w") as fh:
    fh.write("class_name SpriteCrops\n")
    fh.write("## Generated by tools/gen_crops.py. Visible rect of each big sprite.\n\n")
    fh.write("const RECTS := {\n" + "\n".join(rows) + "\n}\n\n\n")
    fh.write("""## Texture that draws only the visible rect but keeps the full size,
## so it lines up exactly like the original.
static func cropped(name: String, tex: Texture2D) -> Texture2D:
\tif not RECTS.has(name):
\t\treturn tex
\tvar r: Rect2 = RECTS[name]
\tvar at := AtlasTexture.new()
\tat.atlas = tex
\tat.region = r
\tat.margin = Rect2(r.position, tex.get_size() - r.size)
\tat.filter_clip = true
\treturn at
""")
print(f"wrote {os.path.normpath(out)} ({len(rows)} sprites)")
